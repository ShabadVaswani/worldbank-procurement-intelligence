"""Procurement reference numbers: normalisation, STEP activity ids and matching tiers.

Most references are generated by STEP (the World Bank's procurement tracking system) as
COUNTRY-AGENCY-ACTIVITYID-CATEGORY-METHOD, e.g. 'MZ-MISAU-458432-GO-RFB'. The activity id is
unique to one procurement activity, so it survives the edits people make to the rest of the
string (a missing hyphen, a typed space, a '-2' suffix). Older or manual references
('45/C/PRAPS/2019') have no activity id and are matched on the whole string.

Matching tiers, strongest first (stored with every link so users can filter on them):
  exact_reference    same normalised reference
  step_activity_id   same STEP activity id
  reference_variant  one reference is the other plus a short letter suffix or infix, the usual
                     way a lot or a re-issue is marked ('EMCRP/G-06A' vs 'EMCRP/G-06',
                     '17B/W/DNAAS/2018' vs '17/W/DNAAS/2018', '...104287 BIS-GO-RFB')
A general fuzzy ratio was tried and rejected: at 0.9 it also matched different packages that
differ by one letter or digit ('TCP/CON/QCBS/B1/G' vs '.../B1/D', 'ENU-02-22' vs 'ENU-03-22').
"""
from __future__ import annotations

import re

from unidecode import unidecode

# the activity id is the 5-7 digit block right before the category code; the lookarounds stop it matching inside longer
# numbers or words
_STEP_ID = re.compile(r"(?<![0-9])([0-9]{5,7})\s*-\s*(?:GO|CW|CS|NC)(?![A-Z])")
_NON_ALNUM = re.compile(r"[^A-Z0-9]+")

TIER_EXACT = "exact_reference"
TIER_STEP = "step_activity_id"
TIER_VARIANT = "reference_variant"
MIN_VARIANT_LENGTH = 6    # shorter references ('LOT1', 'RFQ3') are too generic
MAX_VARIANT_INSERT = 3    # 'A', 'BIS', 'LOT' at most


def normalise_reference(ref: str | None) -> str:
    """Upper-case ASCII with every non-alphanumeric removed: 'MZ-UEM- FA-474115-GO-RFB' -> 'MZUEMFA474115GORFB'."""
    if not ref:
        return ""
    return _NON_ALNUM.sub("", unidecode(ref).upper())


def step_activity_id(ref: str | None) -> str | None:
    """The STEP activity id inside a reference, or None: 'IN-DPO, KANGRA-494415-CW-RFQ' -> '494415'."""
    if not ref:
        return None
    match = _STEP_ID.search(unidecode(ref).upper())
    return match.group(1) if match else None


def is_reference_variant(a: str, b: str) -> bool:
    """True if one normalised reference equals the other with one block of 1-3 letters inserted.

    No digits may be inserted ('TENDER1' vs 'TENDER12' are different lots), and the shorter
    reference must have at least MIN_VARIANT_LENGTH characters.
    """
    short, long_ = (a, b) if len(a) <= len(b) else (b, a)
    extra = len(long_) - len(short)
    if not 1 <= extra <= MAX_VARIANT_INSERT or len(short) < MIN_VARIANT_LENGTH:
        return False
    # try every insertion point: the extra letters can be a prefix, an infix ('17B/W/...') or a suffix ('...06A')
    for start in range(len(short) + 1):
        inserted = long_[start:start + extra]
        if inserted.isalpha() and long_[:start] + long_[start + extra:] == short:
            return True
    return False


def variant_keys(normalised: str) -> list[str]:
    """Every string obtained by deleting one block of 1-3 letters from a normalised reference.

    Joining these keys against other references' normalised form finds all reference_variant
    pairs with an equi-join (no pairwise comparison), e.g. 'EMCRPG06A' -> [..., 'EMCRPG06', ...].
    """
    keys: set[str] = set()
    for size in range(1, MAX_VARIANT_INSERT + 1):
        # deleting more would leave a key too short to be specific, and keys only get shorter as size grows
        if len(normalised) - size < MIN_VARIANT_LENGTH:
            break
        for start in range(len(normalised) - size + 1):
            if normalised[start:start + size].isalpha():
                keys.add(normalised[:start] + normalised[start + size:])
    return sorted(keys)


def match_tier(notice_ref: str | None, contract_ref: str | None) -> str | None:
    """How a notice reference matches a contract reference: a tier name, or None.

    Only meaningful *within the same project*; callers block on project_id first.
    """
    na, nb = normalise_reference(notice_ref), normalise_reference(contract_ref)
    if not na or not nb:
        return None
    if na == nb:
        return TIER_EXACT
    sa, sb = step_activity_id(notice_ref), step_activity_id(contract_ref)
    if sa and sa == sb:
        return TIER_STEP
    if sa and sb:            # two different STEP activities: never the same tender
        return None
    return TIER_VARIANT if is_reference_variant(na, nb) else None
