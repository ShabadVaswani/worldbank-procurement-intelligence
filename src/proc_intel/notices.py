"""Parsing the HTML body of procurement notices.

Contract Award notices generated by STEP follow two templates:
- the full award notice: header (project, reference, method, scope), "Date Notification of Award
  Issued", contract duration, then sections "Awarded Bidder(s)" / "Evaluated Bidder(s)" /
  "Rejected Bidder(s)" (consultant selections say "Firm(s)");
- the "Small Assignment Contract Award" (direct and small contracts): "Contract Signature Date",
  duration, and one section "Awarded Firm/Individual".
Every firm appears as <b>NAME (SUPPLIER_ID)</b>, usually followed by its address and
"Country: <name>". Some firms are printed without an id; they cannot be keyed and are skipped.

Only firm names, ids and countries are extracted. The beneficial-ownership tables that some
notices carry (names and nationalities of private persons) are deliberately ignored.
"""
from __future__ import annotations

import html
import re
from datetime import date

_SECTION = re.compile(
    r"<u>\s*<b>\s*(Awarded|Evaluated|Rejected)\s+(?:Bidder\(s\)|Firm\(s\)|Firm/Individual):?\s*</b>\s*</u>", re.I)
# A firm: bold "NAME (ID)", then (without crossing the next bold tag) an optional "Country: X".
_FIRM = re.compile(r"<b>\s*([^<]*?)\s*\((\d{3,9})\)\s*</b>((?:(?!<b>).)*)", re.S)
_COUNTRY = re.compile(r"Country:\s*([^<\n]+)")
_AWARD_DATE = re.compile(r"Date Notification of Award Issued.*?(\d{4})/(\d{2})/(\d{2})", re.S)
_DURATION = re.compile(r"Duration of Contract.*?(\d+)\s*(Day|Week|Month|Year)", re.S | re.I)
DAYS_PER_UNIT = {"day": 1, "week": 7, "month": 30, "year": 365}   # months and years approximate
_OWNERSHIP = re.compile(r"Beneficial Ownership Details", re.I)
_TAG = re.compile(r"<[^>]+>")
_SPACE = re.compile(r"\s+")


def html_to_text(markup: str | None) -> str:
    """Plain text of a notice: tags removed, entities decoded, whitespace collapsed."""
    if not markup:
        return ""
    return _SPACE.sub(" ", html.unescape(_TAG.sub(" ", markup))).strip()


def _firms_in(segment: str, role: str) -> list[dict]:
    """Firms in one section, first occurrence of each id only."""
    segment = _OWNERSHIP.split(segment, maxsplit=1)[0]          # never read ownership tables
    firms: dict[str, dict] = {}
    for name, supplier_id, tail in _FIRM.findall(segment):
        if supplier_id in firms:
            continue
        country = _COUNTRY.search(tail)
        firms[supplier_id] = {"supplier_id": supplier_id, "name": html.unescape(name).strip(),
                              "country_name": country.group(1).strip() if country else None, "role": role}
    return list(firms.values())


def _parse_date(match: re.Match | None) -> date | None:
    if not match:
        return None
    try:
        return date(int(match.group(1)), int(match.group(2)), int(match.group(3)))
    except ValueError:
        return None


def parse_award_notice(markup: str | None) -> dict:
    """Award date, duration and the firms named in a Contract Award notice body.

    Returns award_notification_date (date or None; full template only), contract_duration_days
    (int or None; months counted as 30 days) and
    firms: a list of {supplier_id, name, country_name, role} with role in awarded / evaluated /
    rejected. Joint-venture members are separate firms, so len(firms) counts firms, not bids.
    """
    markup = markup or ""
    marks = list(_SECTION.finditer(markup))
    firms: list[dict] = []
    for i, mark in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(markup)
        firms.extend(_firms_in(markup[mark.end():end], mark.group(1).lower()))
    duration = _DURATION.search(markup)
    return {
        "award_notification_date": _parse_date(_AWARD_DATE.search(markup)),
        "contract_duration_days": (int(duration.group(1)) * DAYS_PER_UNIT[duration.group(2).lower()]
                                   if duration else None),
        "firms": firms,
    }
